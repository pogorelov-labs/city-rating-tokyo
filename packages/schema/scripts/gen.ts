#!/usr/bin/env tsx
/**
 * Codegen for @city-rating/schema.
 *
 * Reads constants.json + schema.json from this package's root and emits:
 *   - ts/constants.ts        (typed constants)
 *   - ts/types.ts            (TS interfaces matching schema.json $defs)
 *   - ts/index.ts            (re-exports)
 *   - python/city_rating_schema/constants.py
 *   - python/city_rating_schema/models.py      (Pydantic v2)
 *   - python/city_rating_schema/__init__.py
 *
 * The output MUST be byte-identical on re-run so CI can assert
 * `npm run gen && git diff --exit-code`. To stay deterministic:
 *   - never read system clock / Math.random / Date.now
 *   - never iterate a plain object's keys via spread or for..of when order
 *     matters — read the explicit ordered arrays from constants.json
 *   - always write files with a trailing newline and 2-space indent
 *
 * Run: `npm run gen` (or `npx tsx scripts/gen.ts`) from packages/schema.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, '..');

// ---------- helpers ----------

const HEADER_TS = `// GENERATED by \`npm run gen\` from packages/schema/{constants,schema}.json.
// DO NOT EDIT BY HAND. Edit the JSON sources and re-run codegen.
`;

const HEADER_PY = `\"\"\"GENERATED by \`npm run gen\` from packages/schema/{constants,schema}.json.
DO NOT EDIT BY HAND. Edit the JSON sources and re-run codegen.\"\"\"
`;

/** Write file, ensuring parent dir exists, with a trailing newline. */
function emit(path: string, content: string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content.endsWith('\n') ? content : content + '\n');
}

/** Snake_case → camelCase (only for filter field names). */
function camel(s: string): string {
  return s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
}

/** Capitalize first letter (used to make TS type names from $ref keys). */
function pascal(s: string): string {
  // snake_case → PascalCase
  return s
    .split('_')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}

/** JSON.stringify with 2-space indent. */
const j = (v: unknown) => JSON.stringify(v, null, 2);

