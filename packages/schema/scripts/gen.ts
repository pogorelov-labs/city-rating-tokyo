// ---------- ts/types.ts ----------

/** Render a TS-safe property name: quote digit-prefixed keys, camelCase snake_keys. */
function tsPropName(key: string): string {
  const camelCased = camel(key);
  if (/^[\d]/.test(camelCased)) return `'${camelCased}'`;
  return camelCased;
}

/** Convert a JSON Schema type to a TS type string. */
function tsType(node: any): string {
  if (typeof node !== 'object' || node === null) return 'unknown';
  if ('$ref' in node) {
    const refName = node.$ref.replace('#/$defs/', '');
    return pascal(refName);
  }
  if (node.enum) {
    return node.enum.map((v: string) => `'${v}'`).join(' | ');
  }
  if (node.type === 'number' || node.type === 'integer') return 'number';
  if (node.type === 'string') return 'string';
  if (node.type === 'boolean') return 'boolean';
  if (Array.isArray(node.type)) {
    // e.g. ["number","null"]
    return node.type
      .map((t: string) => (t === 'null' ? 'null' : tsType({ ...node, type: t })))
      .join(' | ');
  }
  if (node.type === 'array') {
    return `Array<${tsType(node.items)}>`;
  }
  if (node.type === 'object') {
    // Free-form map: {additionalProperties: {...}} with no listed `properties`.
    if ((!node.properties || Object.keys(node.properties).length === 0) && node.additionalProperties) {
      const valT = tsType(node.additionalProperties);
      // If propertyNames constrains keys to rating_key, narrow to RatingKey.
      const keyT = node.propertyNames && node.propertyNames.$ref ? 'RatingKey' : 'string';
      return `Record<${keyT}, ${valT}>`;
    }
    // Inline object with named properties. Indented for nesting inside an
    // interface body (4 spaces so it reads cleanly under a 2-space field).
    const props = node.properties || {};
    const required = new Set(node.required || []);
    const fields = Object.entries(props).map(([k, v]) => {
      const opt = required.has(k) ? '' : '?';
      return `    ${tsPropName(k)}${opt}: ${tsType(v as any)};`;
    });
    if (fields.length === 0) return 'Record<string, never>';
    return `{\n${fields.join('\n')}\n  }`;
  }
  return 'unknown';
}

/** Emit a TS interface from a $def that has type:object. */
function emitTsInterface(name: string, def: any): string {
  const props = def.properties || {};
  const required = new Set<string>(def.required || []);
  const lines: string[] = [];

  if (def.description) {
    lines.push('/**');
    for (const line of String(def.description).split('\n')) {
      lines.push(` * ${line}`);
    }
    lines.push(' */');
  }

  lines.push(`export interface ${pascal(name)} {`);
  for (const [key, val] of Object.entries(props)) {
    const isReq = required.has(key);
    const opt = isReq ? '' : '?';
    lines.push(`  ${tsPropName(key)}${opt}: ${tsType(val as any)};`);
  }
  lines.push('}');
  return lines.join('\n');
}

function emitTsTypes(): string {
  const lines: string[] = [HEADER_TS, ''];

  // 1. String-union enums first (rating_key, confidence_level, etc.)
  const enumDefs = Object.entries(defs).filter(([, d]) => d.enum);
  for (const [name, def] of enumDefs) {
    if (def.description) {
      lines.push('/**');
      for (const l of String(def.description).split('\n')) lines.push(` * ${l}`);
      lines.push(' */');
    }
    lines.push(`export type ${pascal(name)} = ${(def as any).enum.map((v: string) => `'${v}'`).join(' | ')};`, '');
  }

  // 2. Object interfaces in $def declaration order
  const objDefs = Object.entries(defs).filter(([, d]) => d.type === 'object');
  for (const [name, def] of objDefs) {
    lines.push(emitTsInterface(name, def), '');
  }

  return lines.join('\n');
}

// ---------- ts/index.ts ----------

function emitTsIndex(): string {
  return [
    HEADER_TS,
    "export * from './constants.js';",
    "export * from './types.js';",
    '',
  ].join('\n');
}

// ---------- python/city_rating_schema/constants.py ----------

function pyRepr(v: unknown): string {
  if (v === null || v === undefined) return 'None';
  if (typeof v === 'boolean') return v ? 'True' : 'False';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'string') return JSON.stringify(v);
  if (Array.isArray(v)) {
    if (v.length === 0) return '()';
    const inner = v.map(pyRepr).join(', ');
    // tuple-of-tuples stays readable
    return `(\n    ${inner.replace(/, /g, ',\n    ')},\n)`; // not used for scalars
  }
  return JSON.stringify(v, null, 2);
}

