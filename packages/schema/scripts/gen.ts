// ---------- python/city_rating_schema/models.py ----------

/** Map a JSON Schema type → Python type string. Returns null for objects/refs handled by caller. */
function pyType(node: any): string | null {
  if (typeof node !== 'object' || node === null) return 'Any';
  if ('$ref' in node) {
    const refName = node.$ref.replace('#/$defs/', '');
    return pascal(refName);
  }
  if (node.enum) {
    // Literal[...] of strings
    const vals = node.enum.map((v: string) => JSON.stringify(v)).join(', ');
    return `Literal[${vals}]`;
  }
  if (Array.isArray(node.type)) {
    // e.g. ["number", "null"]
    const parts = node.type.map((t: string) => (t === 'null' ? 'None' : pyType({ ...node, type: t })));
    // Deduplicate (None may already be present)
    const unique = Array.from(new Set(parts.filter((p: string) => p !== null)));
    return unique.join(' | ');
  }
  if (node.type === 'number' || node.type === 'integer') return 'float';
  if (node.type === 'string') return 'str';
  if (node.type === 'boolean') return 'bool';
  if (node.type === 'array') {
    const itemT = pyType(node.items) || 'Any';
    return `list[${itemT}]`;
  }
  if (node.type === 'object') {
    // Inline dict with str→number (used by category_mins / preset filters)
    if (node.additionalProperties && typeof node.additionalProperties === 'object') {
      const valT = pyType(node.additionalProperties) || 'Any';
      return `dict[str, ${valT}]`;
    }
    return 'dict';
  }
  return 'Any';
}

function pyFieldName(key: string): { field: string; alias?: string } {
  // The "1k_1ldk" key starts with a digit — not a valid Python identifier.
  // Use an alias: field name is `one_k_1ldk`, alias stays "1k_1ldk".
  // NOTE: "2ldk" also starts with a digit and needs the same treatment.
  if (/^[\d]/.test(key)) {
    // Strip the leading digit(s) + underscore boundary, prefix with `one_`,
    // so "1k_1ldk" → "one_k_1ldk" and "2ldk" → "one_ldk". The alias keeps
    // the original JSON key so wire format round-trips.
    const stripped = key.replace(/^[\d]+_?/, '');
    return { field: `one_${stripped}`, alias: key };
  }
  return { field: key };
}

function emitPydanticModel(name: string, def: any): string {
  const props = def.properties || {};
  const required = new Set<string>(def.required || []);

  // Does any field need an alias (digit-prefixed JSON key)?
  const needsPopulateByName = Object.keys(props).some((k) => /^[\d]/.test(k));

  const out: string[] = [];
  out.push(`class ${pascal(name)}(BaseModel):`);

  // 1. docstring (if any)
  if (def.description) {
    out.push('    """');
    for (const l of String(def.description).split('\n')) out.push(`    ${l}`);
    out.push('    """', '');
  }

  // 2. model_config (if any aliased fields)
  if (needsPopulateByName) {
    out.push('    model_config = ConfigDict(populate_by_name=True)', '');
  }

  // 3. fields
  const fieldLines: string[] = [];
  for (const [key, val] of Object.entries(props)) {
    const isReq = required.has(key);
    const { field, alias } = pyFieldName(key);
    const baseT = pyType(val as any) || 'Any';
    const typeAnn = isReq ? baseT : `Optional[${baseT}]`;
    let rhs: string;
    if (alias) {
      rhs = `Field(..., alias=${JSON.stringify(alias)})`;
    } else if (isReq) {
      rhs = 'Field(...)';
    } else {
      rhs = 'None';
    }
    fieldLines.push(`    ${field}: ${typeAnn} = ${rhs}`);
  }

  if (fieldLines.length === 0) {
    out.push('    pass');
  } else {
    out.push(...fieldLines);
  }
  return out.join('\n');
}

function emitPythonModels(): string {
  const lines: string[] = [HEADER_PY];

  lines.push(
    'from __future__ import annotations',
    '',
    'from typing import Literal, Optional',
    '',
    'from pydantic import BaseModel, ConfigDict, Field',
    '',
  );

  // Enum types — emit as Literal aliases (one line each).
  const enumDefs = Object.entries(defs).filter(([, d]) => d.enum);
  for (const [name, def] of enumDefs) {
    const vals = (def as any).enum.map((v: string) => JSON.stringify(v)).join(', ');
    lines.push(`${pascal(name)} = Literal[${vals}]`);
  }
  if (enumDefs.length > 0) lines.push('');

  // Object models in $def order. Use forward refs if needed.
  const objDefs = Object.entries(defs).filter(([, d]) => d.type === 'object');
  for (const [name, def] of objDefs) {
    lines.push(emitPydanticModel(name, def), '');
  }

  return lines.join('\n');
}

